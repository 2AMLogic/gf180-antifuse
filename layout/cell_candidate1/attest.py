#!/usr/bin/env python3
"""Write the T1 item 2 (analog) attestation for cell_candidate1.gds.

An artifact-anchored `generic` envelope (`klt signoff` "t1_item": 2) binding
the committed stream by path and sha256, with a `provenance.regeneration`
claim (klayout-tools#2887). The claim's `regenerated_hash` is taken from a
live `generate.py --check` run, never from the committed file: `status` is
"pass" only when that run exits 0, so a drifted generator cannot be cited as
passing. Needs `klt` on PATH (pin it: `uvx --from klayout-tools==X.Y.Z`).
Usage: layout/cell_candidate1/attest.py   (run from the repo root)
"""
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

D = Path("layout/cell_candidate1")
gds = D / "cell_candidate1.gds"
digest = "sha256:" + hashlib.sha256(gds.read_bytes()).hexdigest()
version = subprocess.run(["klt", "--version"], capture_output=True, text=True, check=True)
klt_version = version.stdout.split()[-1]

command = f"python3 {D}/generate.py --check"
run = subprocess.run(command.split(), capture_output=True, text=True)
found = re.search(r"sha256 ([0-9a-f]{64})", run.stdout)
ok = run.returncode == 0 and found is not None and "sha256:" + found.group(1) == digest
if not ok:
    print(run.stdout + run.stderr, file=sys.stderr)
envelope = {
    "schema_version": 1,
    "kind": "generic",
    "t1_item": 2,
    "status": "pass" if ok else "fail",
    "source": f"{D}/generate.py",
    "summary": (
        "cell_candidate1 GDS regenerated by its committed generator "
        f"(`{command}` exit {run.returncode}) at klt {klt_version}; the "
        "regenerated stream is byte-identical to the committed one. Evidence "
        "of reproducible layout generation only; not DRC, LVS or simulation."
    ),
    "provenance": {
        "klt_version": klt_version,
        "input": {
            "path": {"path": str(gds), "scope": "repo"},
            "content_hash": digest,
            "role": "layout",
        },
        "regeneration": {
            "generator": command,
            "regenerated_hash": "sha256:" + found.group(1) if found else "",
        },
    },
}
(D / "cell_candidate1.attest.json").write_text(json.dumps(envelope, indent=2) + "\n")
sys.exit(0 if ok else 1)
