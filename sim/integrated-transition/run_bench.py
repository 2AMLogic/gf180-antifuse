#!/usr/bin/env python3
"""sim/integrated-transition -- run the integrated program-to-read bench through `klt sim` and record it.

    python3 sim/integrated-transition/run_bench.py --preflight        # ONE point on the fleet, nothing recorded
    python3 sim/integrated-transition/run_bench.py                    # both slices, all five process corners
    python3 sim/integrated-transition/run_bench.py --slice slice_ii_iii
    python3 sim/integrated-transition/run_bench.py --record-id ID     # resume: reuse reports already on disk
    python3 sim/integrated-transition/run_bench.py --analyze ID       # re-grade the reports of an existing record, print only

* The grid is a `klt sim` request (testbench/<slice>_<process>.request.json, generated by make_bench.py:
  3 temperatures x the point list). This script submits it with `klt sim` and takes the backend from the host
  default ($KLT_SIM_BACKEND=batch on the dispatch workers). It never loops ngspice itself. If a submit fails the
  exact error is printed and the script exits non-zero: it does NOT fall back to a local run.
* It grades the returned per-corner measurements (analyze.py) and writes an append-only record:
      sim/integrated-transition/reports/<record-id>/<slice>_<process>.report.json.gz   raw measurements
        (staged only; once the run is stored the in-tree copies are removed
         and manifests/artifacts/integrated-transition-<record-id>.manifest.json holds them)
      sim/integrated-transition/records/<record-id>.md                                 evidence record
      measurements/integrated-transition/<record-id>.md                                 per-region / per-sub-combination view
      measurements/integrated-transition/<record-id>.csv                                one row per graded point
  Records are never edited; a re-run mints a new <record-id>.

The CLI grades results with analyze.py and re-exports the Markdown and CSV renderers
from render.py. Library callers of write_records supply the Git revision for the record.
"""

from __future__ import annotations

import argparse
import concurrent.futures as cf
import datetime as dt
import gzip
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(HERE))
import analyze as A  # noqa: E402

sys.path.insert(0, str(HERE.parents[1] / "sim"))
from harness import evidence_store as ES  # noqa: E402
from harness import klt as K  # noqa: E402
from harness import report as R  # noqa: E402
from harness.modload import load_module  # noqa: E402

# render.py is loaded once under a fixed unique name (never a bare `import`, which
# would collide in sys.modules with other experiments' sibling modules).
RENDER = load_module(HERE / "render.py", "sim_it_render")

B = A.B
summary_lines = RENDER.summary_lines
write_records = RENDER.write_records


def __getattr__(name: str):
    """Re-export render.py's library surface under this module."""
    try:
        return getattr(RENDER, name)
    except AttributeError:
        raise AttributeError(f"module {__name__!r} has no attribute {name!r}") from None


def __dir__() -> list[str]:
    """dir() parity: dir() does not consult __getattr__."""
    return sorted(set(globals()) | {n for n in dir(RENDER) if not n.startswith("_")})


def git(*a):
    return R.git_out(REPO, *a)


# ---------------------------------------------------------------------------
# Running klt sim
# ---------------------------------------------------------------------------


def run_klt(request: Path, backend: str | None, outdir: Path) -> dict:
    return K.run_klt_or_exit(request, outdir, backend, retry=K.FIXED_WAIT)


def compact(rep: dict) -> dict:
    """Raw measurements of a klt report in a compact, lossless-for-grading form (names once, values per corner)."""
    names = [x["name"] for x in rep["corners"][0]["measurements"]] if rep["corners"] else []
    pts = []
    for c in rep["corners"]:
        mm = {x["name"]: x["value"] for x in c["measurements"]}
        pts.append({"process": c["process"], "temperature_c": c["temperature_c"], "status": c["status"],
                    "supply_v": c["supply_v"], "values": [mm.get(n) for n in names]})
    env = rep.get("environment", {})
    return {"schema": "integrated-transition-compact-1", "names": names, "points": pts,
            "summary": {k: rep.get(k) for k in ("status", "corner_count", "passed", "failed", "errored", "inconclusive")},
            "engine": f"{env.get('engine')} {env.get('engine_version')}", "remote": env.get("remote"),
            "pdk": (rep.get("provenance") or {}).get("pdk")}


def expand(comp: dict) -> list[dict]:
    return [{"process": p["process"], "temperature_c": p["temperature_c"], "status": p["status"],
             "supply_v": p["supply_v"],
             "measurements": [{"name": n, "value": v} for n, v in zip(comp["names"], p["values"])]}
            for p in comp["points"]]


def save(path: Path, comp: dict):
    path.parent.mkdir(parents=True, exist_ok=True)
    with gzip.open(path, "wt", compresslevel=9) as f:
        f.write(json.dumps(comp, separators=(",", ":")) + "\n")


def load(path: Path) -> dict:
    with gzip.open(path, "rt") as f:
        return json.loads(f.read())



def grade_slice(sl: str, comps: dict) -> tuple[list[dict], dict, int, list[str]]:
    man = json.loads((B.TB_DIR / f"probes_{sl}.json").read_text())
    rows, stress, bad, why = [], {}, 0, []
    for (proc, tier), comp in comps.items():
        for c in expand(comp):
            try:
                r = A.grade(sl, c)
                tag = f"{sl}/{proc}/{c['temperature_c']}C/x{r['scale']:.1f}/{r['scen']}/{r['var']}/sel=({r['cell'][0]},{r['cell'][1]})"
                r["tag"], r["slice"] = tag, sl
                st = A.aggregate_stress(A.stress_rows(sl, c, r, man), tag)
            except A.Ungradable as e:
                bad += 1
                if len(why) < 5:
                    why.append(f"{sl}/{proc}/{c['temperature_c']}C: {e}")
                continue
            rows.append(r)
            A.merge_stress(stress, st)
    return rows, stress, bad, why


# ---------------------------------------------------------------------------


def preflight(backend):
    """One point at two temperatures (two units, so klt sends it to the batch fleet) on the configured backend; nothing is recorded."""
    sl = "slice_i_ii"
    req = json.loads((B.TB_DIR / f"{sl}_typical.request.json").read_text())
    for k, v in req["corners"]["supply_v"].items():
        req["corners"]["supply_v"][k] = v[:1]
    req["corners"]["temperature_c"] = [27, 125]   # two units: a single unit would stay local
    req["remote"] = {"hosts": 2}
    path = B.TB_DIR / "_preflight.request.json"
    path.write_text(json.dumps(req))
    try:
        rep = run_klt(path, backend, Path("/tmp") / "klt-sim-integrated-preflight")
    finally:
        path.unlink(missing_ok=True)
    for cc in rep["corners"]:
        print(f"  corner {cc['corner_id']}: {cc['status']} {[d.get('message', '')[:160] for d in cc.get('diagnostics', [])[:3]]}")
    c = rep["corners"][0]
    nm = sum(1 for x in c["measurements"] if x["value"] is None)
    print(f"preflight: status={rep['status']} corner status={c['status']} measurements without value: {nm}/{len(c['measurements'])}")
    print("remote:", json.dumps((rep.get("environment") or {}).get("remote"), default=str)[:600])
    try:
        g = A.grade(sl, c)
        print("graded:", {k: g[k] for k in ("scen", "var", "dec_ok", "t_dec", "t_settle", "off_dev")}, g["chk"])
    except A.Ungradable as e:
        print("not gradable:", e)
    return 0 if nm == 0 else 3


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--slice", action="append", choices=list(B.SLICE_CELLS))
    ap.add_argument("--process", action="append", choices=list(B.PROCESS))
    ap.add_argument("--backend", default=None, help="klt sim backend override (default: host default)")
    ap.add_argument("--preflight", action="store_true")
    ap.add_argument("--record-id", help="resume an interrupted run (reuses reports already on disk)")
    ap.add_argument("--analyze", metavar="RECORD_ID", help="re-grade the reports of an existing record and print only")
    ap.add_argument("--workers", type=int, default=2, help="concurrent submits (default 2; the fleet caps concurrency)")
    a = ap.parse_args()
    slices = a.slice or list(B.SLICE_CELLS)
    procs = a.process or list(B.PROCESS)

    if any((not p.exists()) or p.read_text() != t for p, t in B.outputs().items()):
        print("ERROR: testbench/ is stale; run make_bench.py first.", file=sys.stderr)
        return 1
    if a.preflight:
        return preflight(a.backend)

    now = dt.datetime.now(dt.timezone.utc)
    record_id = a.analyze or a.record_id or f"{now:%Y%m%d-%H%M%S}-{git('rev-parse', '--short', 'HEAD')}"
    repdir = HERE / "reports" / record_id
    if a.analyze:
        # --analyze reads a finished run: once stored, the in-tree reports are
        # gone, so resolve via the store (no manifest -> run dir, unchanged).
        repdir = ES.run_dir_for_reading("integrated-transition", a.analyze, REPO, repdir)
    clean = not R.git_is_dirty(REPO)

    todo = [(sl, p, t) for sl in slices for p in procs for t in B.TIER_POINTS]
    comps: dict = {sl: {} for sl in slices}

    def one(job):
        sl, proc, tier = job
        sfx = "" if tier == "A" else "_x"
        path = repdir / f"{sl}_{proc}{sfx}.report.json.gz"
        if path.exists():
            return sl, proc, tier, load(path), path
        if a.analyze:
            raise SystemExit(f"--analyze: {path} missing")
        rep = run_klt(B.TB_DIR / B.request_name(sl, proc, tier), a.backend,
                      Path("/tmp") / f"klt-sim-{record_id}-{sl}-{proc}{sfx}")
        comp = compact(rep)
        save(path, comp)    # saved as soon as it returns, so an interrupted run can be resumed
        return sl, proc, tier, comp, path

    with cf.ThreadPoolExecutor(max_workers=max(1, a.workers)) as ex:
        for sl, proc, tier, comp, path in ex.map(one, todo):
            comps[sl][(proc, tier)] = comp
            print(f"{sl}/{proc}/tier {tier}: {comp['summary']}", flush=True)

    all_rows, stress, bad_total, why = [], {}, 0, []
    for sl in slices:
        rows, st, bad, w = grade_slice(sl, comps[sl])
        all_rows += rows
        A.merge_stress(stress, st)
        bad_total += bad
        why += w
        print(f"{sl}: graded {len(rows)}, not gradable {bad}")
    for w in why:
        print("  not gradable:", w)
    if not all_rows:
        print("ERROR: nothing gradable; no record written.", file=sys.stderr)
        return 1
    rec_lines = "\n".join(summary_lines(all_rows))
    print(rec_lines)
    if a.analyze:
        return 0
    write_records(record_id, all_rows, stress, comps, bad_total, clean, now, git("rev-parse", "HEAD"))
    return ES.publish_for_runner("integrated-transition", record_id, repdir, REPO)


if __name__ == "__main__":
    raise SystemExit(main())
