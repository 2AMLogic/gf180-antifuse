#!/usr/bin/env python3
"""Generate the checked-in `klt sim` request set for the cell-device
characterization PVT campaign (issue #63).

    python3 sim/cell-device-characterization/klt/mk_klt_requests.py

Writes `requests/c<N>_access-<s>_cap-<g>/{body.spice,ioff.json,ron.json}`
(3 candidates x 2 access sizings x 2 capacitor geometries = 12 sub-
configurations, 2 requests each = 24 requests) plus `requests/design.ngspice`
(a verbatim copy of the PDK's global-switch include, staged with the request
because off-host klt does not expand $PDK_ROOT in a netlist).

The cell DUT is the committed `design/netlists/cell_candidateN.spice`,
`.include`d unchanged. The corner axes are expressed natively:

  corners.process      access-device MOS section bundled with moscap_typical
                       (Candidate 2 also binds smbb000149's section) -- the
                       same three `.lib` cards the legacy harness emitted
  corners.temperature_c  -40 / 27 / 125
  corners.supply_v     read voltage on vbl (0.9 / 1.0 / 1.1 V). For the I_off
                       request vwl is enumerated alongside vbl so the cross
                       product (3 read voltages x 3 OFF-gate biases) is
                       listed explicitly -- supply_v keys move together by
                       index, they are not crossed.

Geometry/sizing (wacc, wcap) is NOT a klt corner axis: klt `alter` cannot
re-evaluate a sub-circuit instance parameter, so each (sizing, geometry)
sub-configuration is its own netlist body and request. See the experiment
README ("klt sim campaign").

Two requests per sub-configuration because a request carries one analysis:
`ioff.json` (dc point sweep, 135 units) and `ron.json` (ac at 10 MHz, 45 units).
The capacitor C-V bench is NOT migrated (see README).
"""

from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
EXP = HERE.parent
REPO = EXP.parent.parent
sys.path.insert(0, str(EXP))

import importlib.util  # noqa: E402

_spec = importlib.util.spec_from_file_location("run_experiment", EXP / "run_experiment.py")
RE = importlib.util.module_from_spec(_spec)
sys.modules["run_experiment"] = RE
_spec.loader.exec_module(RE)

from harness import corners as C  # noqa: E402
from harness import numfmt as NF  # noqa: E402
from harness import pdk as P  # noqa: E402

REQ_DIR = HERE / "requests"
PDK_VARIANT = "gf180mcuD"
MODELS_LIB = "libs.tech/ngspice/sm141064.ngspice"
SMBB_LIB = "libs.tech/ngspice/smbb000149.ngspice"
MEASPREC = "set measureprec=7"
READ_V = [round(RE.V_READ_NOM * m, 6) for m in (0.9, 1.0, 1.1)]


def process_axis(cand) -> list[dict]:
    out = []
    for mos in C.MOS_CORNERS:
        sections: list = [mos]
        if "smbb000149" in cand.extra_mos_libs:
            sections.append({"lib": SMBB_LIB, "section": mos})
        sections.append("moscap_typical")
        out.append({"name": mos, "sections": sections})
    return out


def body_text(cand, wcap, lcap, wacc, lacc, sizing, geometry) -> str:
    rel = f"../../../../../design/netlists/{cand.netlist}"
    f = NF.fmt
    return (
        f"* GENERATED by klt/mk_klt_requests.py -- do not edit.\n"
        f"* Candidate {cand.n} (Region {cand.region}), access-{sizing}_cap-{geometry}.\n"
        f"* Circuit body for `klt sim`: models/.temp/analysis are supplied by the request.\n"
        f".include \"../design.ngspice\"\n"
        f".include \"{rel}\"\n"
        f".options gmin={f(RE.GMIN)}\n"
        f"X1 BL WL PL VB {cand.subckt} wcap={f(wcap)} lcap={f(lcap)} wacc={f(wacc)} lacc={f(lacc)}\n"
        f"VVB VB 0 DC {f(cand.vb)}\n"
        f"VBL BL 0 DC {f(RE.V_READ_NOM)} AC 1\n"
        f"VWL WL 0 DC {f(cand.wl_on)}\n"
        f"VPL PL 0 DC 0\n"
    )


def common(cand) -> dict:
    return {
        "netlist": "body.spice",
        "engine": "ngspice",
        "netlist_source": "schematic",
        "models": {"pdk": PDK_VARIANT, "lib": MODELS_LIB},
        "options": {"timeout_s": 300, "keep_artifacts": False, "stage_model_inputs": False},
    }


def ioff_request(cand) -> dict:
    lo, mid, hi = RE.off_levels(cand)
    vbl, vwl = [], []
    for v in READ_V:
        for off in (lo, mid, hi):
            vbl.append(v)
            vwl.append(round(off, 6))
    req = common(cand)
    req["corners"] = {
        "process": process_axis(cand),
        "supply_v": {"vbl": vbl, "vwl": vwl},
        "temperature_c": list(C.TEMPS_C),
    }
    # A single-point `dc` sweep of the (unconnected-at-DC) plate source stands
    # in for `.op`: klt `.meas` has no `op` type, and the `measurements[].expr`
    # form was found to fail on the batch backend for any multi-unit request
    # (tool-gap issue filed; see README), so the supported `.meas` form is used.
    # The branch current is reported signed; |.| is taken at ingest.
    req["analysis"] = {"kind": "dc", "args": "vpl 0 0 1"}
    req["measurements"] = [{"name": "ibl", "spice": ".meas dc ibl MAX i(vbl)", "unit": "A"}]
    req["options"]["ngspice_init"] = [MEASPREC]
    return req


def ron_request(cand) -> dict:
    req = common(cand)
    req["corners"] = {
        "process": process_axis(cand),
        "supply_v": {"vbl": list(READ_V), "vwl": [cand.wl_on] * len(READ_V)},
        "temperature_c": list(C.TEMPS_C),
    }
    req["analysis"] = {"kind": "ac", "args": "lin 1 1e7 1e7"}
    # Raw complex branch current + node voltage at the single AC point;
    # R_on = Re(V/(-I)) is computed at ingest (ac `.meas` has no complex
    # arithmetic: `real()` is not a legal function there).
    req["measurements"] = [
        {"name": "ire", "spice": ".meas ac ire MAX vr(vbl#branch)", "unit": "A"},
        {"name": "iim", "spice": ".meas ac iim MAX vi(vbl#branch)", "unit": "A"},
        {"name": "vre", "spice": ".meas ac vre MAX vr(bl)", "unit": "V"},
        {"name": "vim", "spice": ".meas ac vim MAX vi(bl)", "unit": "V"},
    ]
    req["options"]["ngspice_init"] = [MEASPREC]
    return req


def sub_dir_name(cand, sizing, geometry) -> str:
    return f"c{cand.n}_access-{sizing}_cap-{geometry}"


def main() -> int:
    pdk = P.resolve_pdk()
    REQ_DIR.mkdir(parents=True, exist_ok=True)
    (REQ_DIR / "design.ngspice").write_text(pdk.design_ngspice.read_text())
    n = 0
    for cand in RE.CANDIDATES:
        d = RE.parse_defaults(REPO / "design" / "netlists" / cand.netlist)
        for sizing in RE.SIZING_LEVELS:
            for geometry in RE.GEOM_LEVELS:
                wacc = d["wacc"] * RE.sizing_multiplier(sizing)
                wcap = d["wcap"] * RE.sizing_multiplier(geometry)
                sd = REQ_DIR / sub_dir_name(cand, sizing, geometry)
                sd.mkdir(parents=True, exist_ok=True)
                (sd / "body.spice").write_text(body_text(cand, wcap, d["lcap"], wacc, d["lacc"], sizing, geometry))
                (sd / "ioff.json").write_text(json.dumps(ioff_request(cand), indent=2) + "\n")
                (sd / "ron.json").write_text(json.dumps(ron_request(cand), indent=2) + "\n")
                n += 2
    print(f"wrote {n} requests under {REQ_DIR}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
