#!/usr/bin/env python3
"""Generate the paired schematic-vs-extracted `klt sim` request set for the
post-layout access-device probe (issue #447).

    python3 sim/cell-device-characterization/klt/post-layout/mk_post_layout_requests.py

For each of Candidates 1, 3 and 2 (probe order), writes
`requests/c<N>_{schematic,extracted}/{body.spice,ioff.json,ron.json}`
plus `requests/c<N>/provenance.json` (pin map + both DUT hashes) and stages
`requests/design.ngspice` (copy of the schematic campaign's staged global-
switch include).

Both legs stage one DUT each:

  schematic  `.include`s the cell's fixed-geometry
             `layout/<cell>/lvs_reference.spice` (the same netlist `klt pex`
             was given as `--reference-netlist`) and instantiates its four
             ports in the reference's declared order, with no sizing
             overrides -- the drawn geometry, not the schematic campaign's
             parameterised defaults.
  extracted  `.include`s `layout/<cell>/pex/extracted.spice` verbatim and
             instantiates the emitted `.SUBCKT` in ITS pin order (parsed from
             the file, never assumed -- extraction promotes pins
             alphabetically, `BL PL VB WL`, not the reference's
             `BL WL PL VB`).  The name-identical map is recorded in
             `provenance.json`.

Corner/measurement builders are reused from `../mk_klt_requests.py`
verbatim; only the corner axes differ -- each request carries just the one
bound corner the probe reports (issue #447):

  ioff  ff, 125 degC, vbl = 1.1 V, vwl enumerated over the bench's three
        OFF-gate biases (3 units) -- worst |I(VBL)| is taken at ingest
  ron   ss, -40 degC, vbl = 0.9 V, vwl = the candidate's on-gate bias
        (1 unit) -- Re(VBL / -I(VBL)) at 10 MHz, computed at ingest

`netlist_source` is `schematic` / `extracted` respectively.  Supplies, body
connection, model sections, solver settings and measurements are identical
on both legs.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent          # .../klt/post-layout
KLT = HERE.parent                                # .../klt
EXP = KLT.parent                                 # .../cell-device-characterization
REPO = EXP.parent.parent
sys.path.insert(0, str(KLT))
sys.path.insert(0, str(EXP))
sys.path.insert(0, str(EXP.parent))

import mk_klt_requests as MK  # noqa: E402
sys.path.insert(0, str(HERE))
from extraction_check import check_extraction  # noqa: E402
from harness import numfmt as NF  # noqa: E402
from harness.modload import load_module  # noqa: E402

RE = load_module(EXP / "run_experiment.py", "run_experiment")

REQ_DIR = HERE / "requests"
PROBE_ORDER = (1, 3, 2)      # issue #447's table order
IOFF_BOUND = ("ff", 125, 1.1)
RON_BOUND = ("ss", -40, 0.9)


def sha256(path: Path) -> str:
    return "sha256:" + hashlib.sha256(path.read_bytes()).hexdigest()


def subckt_pins(netlist: Path, top: str) -> list[str]:
    """Pin list of `<top>`'s .subckt line, in declared order."""
    pat = re.compile(rf"^\.subckt\s+{re.escape(top)}\b(.*)$", re.IGNORECASE)
    for line in netlist.read_text().splitlines():
        m = pat.match(line.strip())
        if m:
            return m.group(1).split()
    raise ValueError(f"no .subckt {top} found in {netlist}")


def bound_process_axis(cand, proc: str) -> list[dict]:
    entry = next(e for e in MK.process_axis(cand) if e["name"] == proc)
    return [entry]


def rel_include(target: Path, req_dir: Path) -> str:
    return os.path.relpath(target, start=req_dir).replace(os.sep, "/")


def body_text(cand, leg: str, dut_rel: str, x_order: list[str]) -> str:
    f = NF.fmt
    return (
        f"* GENERATED by klt/post-layout/mk_post_layout_requests.py -- do not edit.\n"
        f"* Candidate {cand.n} (Region {cand.region}) post-layout access-device probe,\n"
        f"* {leg} leg (issue #447).  Circuit body for `klt sim`: models/.temp/analysis\n"
        f"* are supplied by the request.  DUT include: {dut_rel}\n"
        f'.include "../design.ngspice"\n'
        f'.include "{dut_rel}"\n'
        f".options gmin={f(RE.GMIN)}\n"
        f"X1 {' '.join(x_order)} {cand.subckt}\n"
        f"VVB VB 0 DC {f(cand.vb)}\n"
        f"VBL BL 0 DC {f(RE.V_READ_NOM)} AC 1\n"
        f"VWL WL 0 DC {f(cand.wl_on)}\n"
        f"VPL PL 0 DC 0\n"
    )


def bound_request(cand, which: str, source: str) -> dict:
    """The schematic campaign's request builder with the corner axes replaced
    by the single bound corner; analysis/measurements/options reused verbatim."""
    req = MK.ioff_request(cand) if which == "ioff" else MK.ron_request(cand)
    if which == "ioff":
        lo, mid, hi = RE.off_levels(cand)
        proc, temp, vbl = IOFF_BOUND
        req["corners"] = {
            "process": bound_process_axis(cand, proc),
            "supply_v": {"vbl": [vbl] * 3, "vwl": [round(v, 6) for v in (lo, mid, hi)]},
            "temperature_c": [temp],
        }
    else:
        proc, temp, vbl = RON_BOUND
        req["corners"] = {
            "process": bound_process_axis(cand, proc),
            "supply_v": {"vbl": [vbl], "vwl": [cand.wl_on]},
            "temperature_c": [temp],
        }
    req["netlist_source"] = source
    return req


def emit_leg(cand, leg: str, dut: Path, x_order: list[str]) -> dict:
    sd = REQ_DIR / f"c{cand.n}_{leg}"
    sd.mkdir(parents=True, exist_ok=True)
    dut_rel = rel_include(dut, sd)
    (sd / "body.spice").write_text(body_text(cand, leg, dut_rel, x_order))
    for which in ("ioff", "ron"):
        (sd / f"{which}.json").write_text(json.dumps(bound_request(cand, which, leg), indent=2) + "\n")
    return {"leg": leg, "dut": str(dut.relative_to(REPO)), "dut_sha256": sha256(dut),
            "subckt_pin_order": x_order}


def main() -> int:
    REQ_DIR.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(KLT / "requests" / "design.ngspice", REQ_DIR / "design.ngspice")
    n = 0
    bad = 0
    for cand in RE.CANDIDATES:
        if cand.n not in PROBE_ORDER:
            continue
        findings = check_extraction(REPO, cand.n)
        pd = REQ_DIR / f"c{cand.n}"
        pd.mkdir(parents=True, exist_ok=True)
        if findings:
            # No pair is emitted for an unusable extraction; the finding is
            # recorded where the runner (and a replay) will see it.
            (pd / "extraction_finding.json").write_text(json.dumps({"findings": findings}, indent=2) + "\n")
            print(f"c{cand.n}: EXTRACTION UNUSABLE, no requests emitted: {'; '.join(findings)}", file=sys.stderr)
            bad += 1
            continue
        (pd / "extraction_finding.json").unlink(missing_ok=True)
        layout_dir = REPO / "layout" / f"cell_candidate{cand.n}"
        ref = layout_dir / "lvs_reference.spice"
        ext = layout_dir / "pex" / "extracted.spice"
        ref_pins = subckt_pins(ref, cand.subckt)
        ext_pins = subckt_pins(ext, cand.subckt)
        bench = ["BL", "WL", "PL", "VB"]
        assert set(ref_pins) == set(bench), (cand.n, ref_pins)
        assert set(ext_pins) == set(bench), (cand.n, ext_pins)
        schematic = emit_leg(cand, "schematic", ref, ref_pins)
        extracted = emit_leg(cand, "extracted", ext, ext_pins)
        # Ordered map: position i of the extracted .SUBCKT header <- the bench
        # net of the same name.  The X line instantiates exactly this order.
        pin_map = [{"position": i + 1, "extracted_pin": p, "bench_net": p} for i, p in enumerate(ext_pins)]
        prov = {
            "cell": f"cell_candidate{cand.n}",
            "gds": f"layout/cell_candidate{cand.n}/cell_candidate{cand.n}.gds",
            "gds_sha256": sha256(layout_dir / f"cell_candidate{cand.n}.gds"),
            "bench_nets": bench,
            "schematic": schematic,
            "extracted": extracted,
            "extracted_pin_map": pin_map,
        }
        (pd / "provenance.json").write_text(json.dumps(prov, indent=2) + "\n")
        n += 2
    print(f"wrote {n} leg request sets ({n} legs x ioff+ron) under {REQ_DIR}")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
