"""Bench generators for sim/program-read-legs/.

Every bench is a netlist BODY for ``klt sim`` (no .control/.end -- klt owns
those and appends the corner's .lib/.temp cards, the analysis, and the
measurements[].expr print block). The device under test is always the
committed design/netlists/*.spice, pulled in with .include -- no device lines
are copied here. klt stages the include closure for the batch fleet.

stdlib only.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "sim"))
from harness import numfmt as NF  # noqa: E402

fmt = NF.fmt
NETLISTS = REPO_ROOT / "design" / "netlists"

# --- assumed / placeholder numbers (each one is labelled wherever reported) --
V_COMPLIANCE_ASSUMED = 1.0   # V across filament+access after breakdown (ASSUMED)
I_TARGET_MAX_ASSUMED = 1e-3  # A, program compliance current (ASSUMED, spec 2 open)
VPP_MAX = 6.0                # V, top of the 6 V device tier (bench rail)
VPP_STEPS = (4.0, 5.0, 6.0)  # V, illustrative program-rail points (ASSUMED)
R_PROG_ASSUMED = {"lo": 10e3, "hi": 100e3}   # ohm, ASSUMED (no breakdown model)
I_REF = 1e-6                 # A, design I_ref (bench-supplied)
I_REF_LOW = 3e-10            # A, alternative I_ref tried for Candidate 3 only
VDD_NOM = 3.3
VCLAMP_NOM = 1.8
VDD_POINTS = (VDD_NOM * 0.9, VDD_NOM, VDD_NOM * 1.1)
VCLAMP_POINTS = (VCLAMP_NOM * 0.9, VCLAMP_NOM, VCLAMP_NOM * 1.1)
VPP_IDLE = 6.0               # V, worst-case (highest) VPP while the leg is off

PDK_DESIGN = "$PDK_ROOT/gf180mcuD/libs.tech/ngspice/design.ngspice"

def cell_defaults(cell: str) -> dict[str, float]:
    return NF.cell_defaults(NETLISTS / f"{cell}.spice")


# Candidate -> bias conventions, carried over from
# sim/cell-device-characterization/run_experiment.py (same WL "fully on" bias).
CANDIDATES = {
    1: dict(cell="cell_candidate1", region="I", wl="tracks_vdd", vb="0"),
    2: dict(cell="cell_candidate2", region="II", wl="5.0", vb="0"),
    3: dict(cell="cell_candidate3", region="III", wl="0", vb="tracks_vdd"),
}


def i_sneak_max(candidate: int) -> float:
    """I_sneak_max out of the committed cell-device-characterization record
    for this candidate (the 'unprogrammed corner' the issue names)."""
    rec_dir = REPO_ROOT / "sim" / "cell-device-characterization" / "records"
    want = f"cell_candidate{candidate}.spice"
    for p in sorted(rec_dir.glob("*.md")):
        t = p.read_text()
        if want in t:
            m = re.search(r"I_sneak_max = ([0-9.]+e[-+][0-9]+) A", t)
            if m:
                return float(m.group(1))
    raise RuntimeError(f"no I_sneak_max record for candidate {candidate}")


def header(title: str, rel_netlists: str) -> list[str]:
    return [
        f"* gf180-antifuse sim/program-read-legs -- {title}",
        "* GENERATED by sim/program-read-legs/benches.py -- do not edit.",
        "* Netlist body for klt sim: no .control/.end (klt appends them).",
        f".include {PDK_DESIGN}",
        f".include {rel_netlists}/leg_interlock.spice",
        f".include {rel_netlists}/program_leg.spice",
        f".include {rel_netlists}/read_leg.spice",
    ]


def common_sources(cand: dict | None = None) -> list[str]:
    return [
        f"VDD vdd 0 DC {fmt(VDD_NOM)}",
        f"VCLAMP vclamp 0 DC {fmt(VCLAMP_NOM)}",
        "* logic highs track VDD (E sources) so the corner's VDD moves them too",
        "EHI hi 0 vdd 0 1",
    ]


# ---------------------------------------------------------------------------
# Margin bench: one netlist per candidate
# ---------------------------------------------------------------------------

SIDES = (("U", None), ("Plo", "lo"), ("Phi", "hi"))
SIZINGS = (("min", 1.0), ("2x", 2.0))


def margin_bench(candidate: int, rel_netlists: str, iref: float = I_REF) -> tuple[str, list[dict]]:
    c = CANDIDATES[candidate]
    d = cell_defaults(c["cell"])
    isn = i_sneak_max(candidate)
    L = header(f"margin bench, Candidate {candidate} (Region {c['region']})", rel_netlists)
    L.append(f".include {rel_netlists}/{c['cell']}.spice")
    L += common_sources()
    L.append("VPL pl 0 DC 0")
    L.append("EWL wl 0 hi 0 1" if c["wl"] == "tracks_vdd" else f"VWL wl 0 DC {c['wl']}")
    L.append("EVB vb 0 hi 0 1" if c["vb"] == "tracks_vdd" else f"VVB vb 0 DC {c['vb']}")
    L.append(f"VPPIDLE vppi 0 DC {fmt(VPP_IDLE)}")
    L.append("* read leg enabled (READ_EN=1, PROG_EN=0); program leg present but OFF")
    L.append("EREN read_en 0 hi 0 1")
    L.append("VPEN prog_en 0 DC 0")
    meas = []
    for side, rkey in SIDES:
        for szname, szmul in SIZINGS:
            t = f"{side}_{szname}"
            L.append(f"* ---- instance {t}: side={side} access sizing={szname} ----")
            L.append(f"XC_{t} bl_{t} wl pl vb {c['cell']} wacc={fmt(d['wacc'] * szmul)}")
            if rkey is not None:
                L.append(f"RPRG_{t} xc_{t}.cn pl {fmt(R_PROG_ASSUMED[rkey])}")
            L.append(f"ISNK_{t} bl_{t} 0 DC {fmt(isn)}")
            L.append(f"VAMR_{t} blr_{t} bl_{t} DC 0")
            L.append(f"VAMP_{t} blp_{t} bl_{t} DC 0")
            L.append(f"XRD_{t} prog_en read_en vclamp iref_{t} vdd 0 blr_{t} sense_{t} rdata_{t} read_leg")
            L.append(f"XPG_{t} prog_en read_en vdd 0 blp_{t} vppi program_leg")
            L.append(f"IREF_{t} 0 iref_{t} DC {fmt(iref)}")
            for q, e in ((f"ird_{t}", f"i(vamr_{t})"), (f"ipg_{t}", f"i(vamp_{t})"),
                         (f"vbl_{t}", f"v(bl_{t})"), (f"vsense_{t}", f"v(sense_{t})"),
                         (f"vrdata_{t}", f"v(rdata_{t})"), (f"vddm_{t}", "v(vdd)")):
                meas.append({"name": q, "expr": e})
    return "\n".join(L) + "\n", meas


# ---------------------------------------------------------------------------
# Mirror-offset bench (Monte Carlo): read leg alone, no cell
# ---------------------------------------------------------------------------

OFFSET_INSTANCES = 4   # independent read-leg instances (independent mismatch draws) per sample


def offset_bench(rel_netlists: str) -> tuple[str, list[dict]]:
    """The sense mirror's input-referred current offset against I_ref.

    Each instance is a read leg whose bit line is loaded by an ideal sink of
    exactly I_REF (the I_ref branch's nominal copy), with SENSE forced to
    VDD/2 by a voltage source. The current through that source,
    ``i_sense = I(MPO) - I(MNO)``, is zero for a perfectly matched mirror and
    equals the mirror's current offset otherwise: the decision threshold is
    I_ref + (offset). No cell is present, so this is candidate-independent.
    """
    L = header("mirror-offset bench (read leg, BL sunk at I_ref, SENSE forced to VDD/2)", rel_netlists)
    L += common_sources()
    L.append("EHALF half 0 vdd 0 0.5")
    L.append("VPEN prog_en 0 DC 0")
    L.append("EREN read_en 0 hi 0 1")
    L.append("VPPIDLE vppi 0 DC %s" % fmt(VPP_IDLE))
    meas = []
    for k in range(OFFSET_INSTANCES):
        t = f"o{k}"
        L.append(f"* ---- instance {t} ----")
        L.append(f"ISNK_{t} bl_{t} 0 DC {fmt(I_REF)}")
        L.append(f"VSNS_{t} sense_{t} half DC 0")
        L.append(f"XRD_{t} prog_en read_en vclamp iref_{t} vdd 0 bl_{t} sense_{t} rdata_{t} read_leg")
        L.append(f"IREF_{t} 0 iref_{t} DC {fmt(I_REF)}")
        meas.append({"name": f"isense_{t}", "expr": f"i(vsns_{t})"})
        meas.append({"name": f"vbl_{t}", "expr": f"v(bl_{t})"})
    return "\n".join(L) + "\n", meas


# ---------------------------------------------------------------------------
# Mutual-exclusion bench
# ---------------------------------------------------------------------------

STATES = ((0, 0), (1, 0), (0, 1), (1, 1))   # (PROG_EN, READ_EN)


def exclusion_cases() -> list[tuple[tuple[int, int], float, str]]:
    """(state, vpp, bl_level) with bl_level in {'0','vpp'}; BL pinned at VPP is
    only applied to states whose read leg is meant to be OFF."""
    cases = []
    for st in STATES:
        for vpp in (3.63, VPP_MAX):
            cases.append((st, vpp, "0"))
            if st != (0, 1):
                cases.append((st, vpp, "vpp"))
    return cases


def case_tag(st, vpp, bl) -> str:
    return f"p{st[0]}r{st[1]}_vpp{vpp:.2f}_bl{bl}".replace(".", "p")


def exclusion_bench(rel_netlists: str) -> tuple[str, list[dict]]:
    L = header("mutual-exclusion bench (both legs on one bit line)", rel_netlists)
    L += common_sources()
    L.append("* BL driven at 0 V (legs would SOURCE current) or at VPP (legs would SINK it)")
    meas = []
    for st, vpp, bl in exclusion_cases():
        t = case_tag(st, vpp, bl)
        L.append(f"* ---- {t} ----")
        L.append(f"VPP_{t} vpp_{t} 0 DC {fmt(vpp)}")
        L.append(f"VBL_{t} bl_{t} 0 DC {fmt(vpp if bl == 'vpp' else 0.0)}")
        L.append(f"EPEN_{t} pen_{t} 0 hi 0 1" if st[0] else f"VPEN_{t} pen_{t} 0 DC 0")
        L.append(f"EREN_{t} ren_{t} 0 hi 0 1" if st[1] else f"VREN_{t} ren_{t} 0 DC 0")
        L.append(f"VAMP_{t} blp_{t} bl_{t} DC 0")
        L.append(f"VAMR_{t} blr_{t} bl_{t} DC 0")
        L.append(f"XPG_{t} pen_{t} ren_{t} vdd 0 blp_{t} vpp_{t} program_leg")
        L.append(f"XRD_{t} pen_{t} ren_{t} vclamp iref_{t} vdd 0 blr_{t} sense_{t} rdata_{t} read_leg")
        L.append(f"IREF_{t} 0 iref_{t} DC {fmt(I_REF)}")
        meas.append({"name": f"ipg_{t}", "expr": f"i(vamp_{t})"})
        meas.append({"name": f"ird_{t}", "expr": f"i(vamr_{t})"})
    return "\n".join(L) + "\n", meas


# ---------------------------------------------------------------------------
# Ballast / compliance bench (program leg alone)
# ---------------------------------------------------------------------------

def ballast_bench(rel_netlists: str) -> tuple[str, list[dict]]:
    L = header("ballast / compliance bench (program leg, BL held at V_compliance)", rel_netlists)
    L += common_sources()
    L.append("EPEN pen 0 hi 0 1")
    L.append("VREN ren 0 DC 0")
    meas = []
    for vpp in VPP_STEPS:
        for vcn, vbl in (("comp", V_COMPLIANCE_ASSUMED), ("short", 0.0)):
            t = f"vpp{vpp:.1f}_{vcn}".replace(".", "p")
            L.append(f"* ---- {t} ----")
            L.append(f"VPP_{t} vpp_{t} 0 DC {fmt(vpp)}")
            L.append(f"VBL_{t} bl_{t} 0 DC {fmt(vbl)}")
            L.append(f"VAM_{t} blp_{t} bl_{t} DC 0")
            L.append(f"XPG_{t} pen ren vdd 0 blp_{t} vpp_{t} program_leg")
            meas.append({"name": f"ipg_{t}", "expr": f"i(vam_{t})"})
            meas.append({"name": f"vrbtop_{t}", "expr": f"v(xpg_{t}.rb_top)"})
            meas.append({"name": f"vpg_{t}", "expr": f"v(xpg_{t}.pg)"})
            meas.append({"name": f"vbl_{t}", "expr": f"v(bl_{t})"})
    return "\n".join(L) + "\n", meas
