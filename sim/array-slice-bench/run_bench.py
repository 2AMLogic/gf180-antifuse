#!/usr/bin/env python3
"""sim/array-slice-bench -- run the slice bench through `klt sim` and record it.

    python3 sim/array-slice-bench/run_bench.py                 # both slices
    python3 sim/array-slice-bench/run_bench.py --slice slice_i_ii
    python3 sim/array-slice-bench/run_bench.py --backend local # debug only
    python3 sim/array-slice-bench/run_bench.py --analyze-report PATH --slice S   # grade one process report only (--no-write implied)
    python3 sim/array-slice-bench/run_bench.py --mode full-band   # issue #70: full-band leakage (fullband.py)

What it does (and does not do)
------------------------------
* The PVT x selected-cell x supply grid is a `klt sim` request
  (testbench/<slice>_<process>.request.json, one per process corner, generated by make_bench.py). This script
  submits it with `klt sim` and takes the backend from the host default
  ($KLT_SIM_BACKEND=batch on the dispatch workers, so the grid goes to the Spot
  batch fleet). It never loops ngspice itself. If the submit fails, the exact
  error is printed and the script exits non-zero - it does NOT fall back to a
  local run of the grid.
* It then grades the returned per-corner measurements against the acceptance
  statements in README.md and writes an append-only record:
      sim/array-slice-bench/reports/<record-id>/<slice>_<process>.report.json   raw reports
        (staged only; once the run is stored the in-tree copies are removed
         and manifests/artifacts/array-slice-bench-<record-id>.manifest.json holds them)
      sim/array-slice-bench/records/<record-id>.md                    record
      measurements/array-slice-bench/<record-id>.md                   per-region
  Records are never edited; a re-run mints a new <record-id>.

Grading is per REGION and per capacitor-geometry x access-sizing sub-combination
(spec/split-axis-plan.md); nothing is averaged across regions or sub-combinations.

The library lives in the siblings model.py (bench thresholds, committed-cell
map, corner grading, per-region aggregation) and render.py (the slice and
full-band Markdown/CSV renderers); this file is the CLI driver and re-exports
their surface, so loading run_bench.py as a library (as the tests do) keeps
every attribute unchanged.
"""

