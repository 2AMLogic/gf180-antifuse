# The library siblings are loaded once each under fixed unique names (never a
# bare `import`, which under python3 -I has no script dir on sys.path and
# would collide in sys.modules with other experiments' sibling modules).
# model first: render.py reuses the already-loaded copy from sys.modules.
M = load_module(HERE / "model.py", "sim_asb_model")
RENDER = load_module(HERE / "render.py", "sim_asb_render")

# The library surface the CLI below calls directly (everything else is
# re-exported lazily through __getattr__).
analyze = M.analyze
slice_section = RENDER.slice_section
write_records = RENDER.write_records
slice_measurement_view = RENDER.slice_measurement_view
_jobs_line = RENDER._jobs_line
fullband_record_body = RENDER.fullband_record_body
fullband_measurement_view = RENDER.fullband_measurement_view
fullband_csv = RENDER.fullband_csv


def __getattr__(name: str):
    """Re-export model.py's and render.py's library surface under this module,
    so `load_module(.../run_bench.py)` callers see the attribute set the
    pre-split single file had."""
    for src in (M, RENDER):
        try:
            return getattr(src, name)
        except AttributeError:
            continue
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")


def __dir__() -> list[str]:
    """dir() parity with the pre-split module: dir() does not consult
    __getattr__, so without this the facade would advertise only its own
    names instead of the library surface callers actually resolve."""
    return sorted(set(globals()) | {n for n in dir(M) + dir(RENDER) if not n.startswith("_")})


def git(*a):
    return R.git_out(REPO, *a)


# ---------------------------------------------------------------------------
# Running klt sim
# ---------------------------------------------------------------------------


def run_klt(sl: str, proc: str, backend: str | None, outdir: Path, request: Path | None = None) -> dict:
    return K.run_klt_or_exit(request or B.TB_DIR / f"{sl}_{proc}.request.json", outdir, backend, retry=K.FIXED_WAIT)


def merge_reports(reps: list[dict]) -> dict:
    """Fold the per-process-corner klt reports of one slice into one view."""
    out = {"corners": [], "corner_count": 0, "passed": 0, "failed": 0, "errored": 0, "inconclusive": 0,
           "environment": reps[0].get("environment", {}), "provenance": reps[0].get("provenance", {}),
           "jobs": []}
    for r in reps:
        out["corners"] += r["corners"]
        for k in ("corner_count", "passed", "failed", "errored", "inconclusive"):
            out[k] += r[k]
        out["jobs"].append((r.get("environment") or {}).get("remote") or {})
    return out


def slim_payload(report: dict) -> tuple[str, str | None]:
    """-> (committed text of a klt report, sha256 of its full text, or None).

    The text is the coverage-elided form (`harness.report.elide_coverage`);
    every measurement value and everything else is kept. The digest commits to
    the full, un-elided text at the same serialisation options (see
    `harness.report.klt_report_payload`): write it beside the report as a
    `<name>.report.json.sha256` sidecar so the elision stays auditable.

    None means no attestable digest: the input was already coverage-elided
    (`harness.report.coverage_is_elided` -- as `--analyze-report` on a
    committed report is), the elision is a no-op on it, and a digest would
    attest the elided text sitting beside the sidecar instead of the raw
    report it claims to attest. Skip the sidecar write in that case -- the
    same carve-out the full-band resume path gets by never re-writing a
    reused report (it cannot digest bytes it never had)."""
    if R.coverage_is_elided(report):
        return R.klt_report_payload(report, indent=None, separators=(",", ":"))[0], None
    return R.klt_report_payload(report, indent=None, separators=(",", ":"))


def write_report_and_digest(rp: Path, payload: tuple[str, str | None]) -> None:
    """Commit the report text, plus its sidecar only when a full-text digest
    was attestable (a None digest means the input was already elided)."""
    text, full_sha = payload
    rp.write_text(text)
    if full_sha is not None:
        R.write_once(rp.with_name(rp.name + ".sha256"), full_sha + "\n")


# ---------------------------------------------------------------------------
# Full-band leakage mode (issue #70)
# ---------------------------------------------------------------------------


def run_full_band(a) -> int:
    import fullband as F   # noqa: E402  (stdlib + gen_array + make_bench only)

    now = dt.datetime.now(dt.timezone.utc)
    record_id = a.record_id or f"{now:%Y%m%d-%H%M%S}-{git('rev-parse', '--short', 'HEAD')}-fullband"
    clean = not R.git_is_dirty(REPO)
    bands = a.band or list(G.BAND_SLICES)
    rep_dir = HERE / "reports" / record_id
    reports: dict[tuple[str, str], dict[str, dict]] = {}
    for name in bands:
        for variant in B.LEAK_VARIANTS:
            reports[(name, variant)] = {}
            for proc in B.PROCESS:
                rp = rep_dir / f"leak_{variant}_{name}_{proc}.report.json"
                if rp.exists():   # resume: a raw report already on disk is never resubmitted or overwritten
                    reports[(name, variant)][proc] = json.loads(rp.read_text())
                    print(f"reusing {rp.relative_to(REPO)}", flush=True)
                    continue
                req = B.TB_DIR / f"leak_{variant}_{name}_{proc}.request.json"
                rep = run_klt(name, proc, a.backend, Path("/tmp") / f"klt-sim-{record_id}-{variant}-{name}-{proc}", req)
                rep_dir.mkdir(parents=True, exist_ok=True)
                write_report_and_digest(rp, slim_payload(rep))
                reports[(name, variant)][proc] = rep
                print(f"wrote {rp.relative_to(REPO)}", flush=True)
    return finish_full_band(F, record_id, clean, now, bands, reports, a)


def finish_full_band(F, record_id, clean, now, bands, reports, a) -> int:
    pg, nat, sel = [], [], []
    jobs = []
    problems = []
    for name in bands:
        for variant, fn, acc in (("pgoff", F.analyze_pgoff, pg), ("nat", F.analyze_nat, nat), ("sel", F.analyze_sel, sel)):
            reps = reports[(name, variant)]
            try:
                acc += fn(name, reps)
            except F.AnalysisError as ex:
                problems.append(f"{name}/{variant}: {ex}")
        for variant in B.LEAK_VARIANTS:
            for proc, r in reports[(name, variant)].items():
                jobs.append(f"- `{variant}` {name} {proc}: " + ", ".join(_jobs_line({proc: r})) +
                            f"; corners {r['corner_count']} (pass {r['passed']}, fail {r['failed']}, error {r['errored']}, "
                            f"inconclusive {r['inconclusive']})")
    if problems:
        print("ERROR: ungradable report(s); no record written:\n  " + "\n  ".join(problems), file=sys.stderr)
        return 3
    sha = git("rev-parse", "HEAD")
    sel_bad = sum(0 if r["ok"] else 1 for r in sel)
    floor_n = sum(1 for r in pg if r["floor_dominated"])
    rec = HERE / "records" / f"{record_id}.md"
    rec.parent.mkdir(parents=True, exist_ok=True)
    rec.write_text(fullband_record_body(F, record_id, sha, clean, now, pg, nat, sel, floor_n, sel_bad, jobs))
    meas = REPO / "measurements" / "array-slice-bench"
    meas.mkdir(parents=True, exist_ok=True)
    (meas / f"{record_id}.md").write_text(fullband_measurement_view(F, record_id, pg, sel))
    (meas / f"{record_id}.csv").write_text(fullband_csv(pg))
    print(f"wrote {rec.relative_to(REPO)}, measurements/array-slice-bench/{record_id}.{{md,csv}}")
    worst = max(pg, key=lambda r: r["total"])
    print(f"worst I_leak,total {worst['total']:.3g} A ({worst['band']} {worst['level']} {worst['process']}/{worst['temp']}C); "
          f"min I_ref/I_leak,total {min(r['ratio'] for r in pg):.3g}; selected-path points below threshold {sel_bad}/{len(sel)}")
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--mode", choices=("slice", "full-band"), default="slice")
    ap.add_argument("--band", action="append", choices=list(G.BAND_SLICES), help="full-band mode: restrict to a band")
    ap.add_argument("--record-id", help="full-band mode: resume an interrupted run (reuses reports already on disk)")
    ap.add_argument("--slice", action="append", choices=list(G.SLICES))
    ap.add_argument("--backend", default=None, help="klt sim backend override (default: host default)")
    ap.add_argument("--analyze-report", type=Path,
                    help="grade an existing klt JSON report (one process request) instead of running; "
                         "grades only -- implies --no-write, nothing is written")
    ap.add_argument("--no-write", action="store_true", help="grade and print only")
    a = ap.parse_args()
    if a.analyze_report and a.mode == "full-band":
        ap.error("--analyze-report cannot be combined with --mode full-band: full-band never grades the report path")
    if a.analyze_report:
        a.no_write = True
        print("note: --analyze-report grades only; nothing is written (--no-write implied)", file=sys.stderr)
    slices = a.slice or list(G.SLICES)

    if any((not p.exists()) or p.read_text() != t for p, t in B.outputs().items()):
        print("ERROR: testbench/ is stale; run make_bench.py first.", file=sys.stderr)
        return 1

    if a.mode == "full-band":
        return run_full_band(a)

    now = dt.datetime.now(dt.timezone.utc)
    record_id = f"{now:%Y%m%d-%H%M%S}-{git('rev-parse', '--short', 'HEAD')}"
    clean = not R.git_is_dirty(REPO)
    sections = []
    worst_bad = 0
    for sl in slices:
        if a.analyze_report:
            reps = [(None, json.loads(a.analyze_report.read_text()))]
        else:
            reps = []
            for proc in B.PROCESS:
                reps.append((proc, run_klt(sl, proc, a.backend, Path("/tmp") / f"klt-sim-{record_id}-{sl}-{proc}")))
        report = merge_reports([r for _p, r in reps])
        payloads = {proc or "all": slim_payload(r) for proc, r in reps}
        per = analyze(sl, report, REPO)
        sec, reach, iso, errors = slice_section(sl, report, per,
                                                {k: s for k, (_t, s) in payloads.items()},
                                                write=not a.no_write)
        sections.append(sec)
        bad = sum(t["bad"] for t in reach.values()) + sum(u["bad"] for u in iso.values()) + errors
        worst_bad += bad
        print(f"{sl}: {report['corner_count']} corners, {bad} criteria violations / ungradable")
        if not a.no_write:
            for proc, _r in reps:
                rp = HERE / "reports" / record_id / f"{sl}_{proc}.report.json"
                rp.parent.mkdir(parents=True, exist_ok=True)
                write_report_and_digest(rp, payloads[proc])

    if a.no_write:
        for s in sections:
            print("\n".join(s))
        return 0 if worst_bad == 0 else 3
    text = write_records(record_id, sections, clean, now, repo=REPO)
    rec = HERE / "records" / f"{record_id}.md"
    rec.parent.mkdir(parents=True, exist_ok=True)
    rec.write_text(text)
    meas = REPO / "measurements" / "array-slice-bench" / f"{record_id}.md"
    meas.parent.mkdir(parents=True, exist_ok=True)
    meas.write_text(slice_measurement_view(record_id, sections))
    print(f"wrote {rec.relative_to(REPO)} and {meas.relative_to(REPO)}")
    if ES.publish_for_runner("array-slice-bench", record_id, HERE / "reports" / record_id, REPO):
        return 1
    return 0 if worst_bad == 0 else 3


if __name__ == "__main__":
    raise SystemExit(main())
