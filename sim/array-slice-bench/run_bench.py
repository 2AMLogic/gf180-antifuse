def run_klt(sl: str, proc: str, backend: str | None, outdir: Path) -> dict:
    cmd = ["klt", "sim", str(B.TB_DIR / f"{sl}_{proc}.request.json"), "--format", "json", "-o", str(outdir)]
    if backend:
        cmd += ["--backend", backend]
    for attempt in range(1, MAX_SUBMITS + 1):
        print(f"running (submit {attempt}/{MAX_SUBMITS}):", " ".join(cmd), flush=True)
        p = subprocess.run(cmd, capture_output=True, text=True)
        blob = p.stdout + p.stderr
        # The fleet is shared: a concurrency-cap or no-capacity refusal is transient
        # and is retried as the SAME batch request after a pause. Nothing else is
        # retried, and a local run is never substituted.
        if ("BATCH_MAX_CONCURRENT_INSTANCES" in blob or "batch_no_capacity" in blob) and attempt < MAX_SUBMITS:
            print(f"  fleet refusal ({'concurrency cap' if 'MAX_CONCURRENT' in blob else 'no capacity'}); "
                  f"waiting {RETRY_WAIT_S}s", flush=True)
            time.sleep(RETRY_WAIT_S)
            continue
        break
    try:
        rep = json.loads(p.stdout)
    except json.JSONDecodeError:
        print(f"ERROR: klt sim produced no JSON (exit {p.returncode}).\n--- stderr ---\n{p.stderr}\n--- stdout ---\n{p.stdout[:2000]}",
              file=sys.stderr)
        raise SystemExit(1)
    if "error" in rep:
        print(f"ERROR: klt sim reported an error (exit {p.returncode}); NOT falling back to a local run:\n"
              f"{json.dumps(rep['error'], indent=2)}", file=sys.stderr)
        raise SystemExit(1)
    return rep


def merge_reports(reps: list[dict]) -> dict:
    """Fold the per-process-corner klt reports of one slice into one view."""
    out = {"corners": [], "corner_count": 0, "passed": 0, "failed": 0, "errored": 0, "inconclusive": 0,
           "environment": reps[0].get("environment", {}), "provenance": reps[0].get("provenance", {}),
           "jobs": []}
    for r in reps:
        out["corners"] += r["corners"]
        for k in ("corner_count", "passed", "failed", "errored", "inconclusive"):
            out[k] += r[k]
        out["jobs"].append((r.get("environment") or {}).get("remote") or {})
    return out


def slim(report: dict) -> dict:
    """Drop the per-measurement coverage bookkeeping (tens of thousands of
    ids that restate 'characterization without limits'); everything else, and
    every measurement value, is kept. The sha256 of the full text is recorded."""
    r = json.loads(json.dumps(report))
    cov = r.get("coverage", {})
    for k in ("checked", "inapplicable"):
        if k in cov:
            cov[k] = f"<{len(cov[k])} entries elided by run_bench.py slim()>"
    return r


